export function lang(): 'nl' | 'en' {
  if (save.lang !== 'auto') return save.lang;
  return (navigator.language || 'en').toLowerCase().startsWith('nl') ? 'nl' : 'en';
}

export function t(key: string): string {
  const d = lang() === 'nl' ? nl : en;
  return d[key] ?? en[key] ?? key;
}
